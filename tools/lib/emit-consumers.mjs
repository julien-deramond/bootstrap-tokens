/**
 * Shapes of the token document for consumers that are not Sass.
 *
 * Each one answers a different question. TypeScript answers "what is the custom property
 * for this token, and what does it hold?" — the question you have when theming React or
 * writing CSS-in-JS, where you want `var(--bs-…)` and autocomplete rather than a colour
 * frozen at build time. Style Dictionary answers "how do I put these in a pipeline that
 * already exists?" and therefore keeps the reference graph, because a pipeline that cannot
 * see that `theme.primary` follows `color.blue.500` cannot re-skin anything. Tokens Studio
 * answers "what does this look like?", which is the only one that needs flat hex, because
 * Figma has no cascade and no `color-mix()`.
 *
 * The differences are the point. Emitting one shape three times would be easier and would
 * make two of the three worse.
 */

import { ext, walk } from './tokens.mjs'
import { splitTopLevel } from './css-lint.mjs'
import { typedToCss } from './value.mjs'
import { flattenValues } from './flatten.mjs'

const unquote = (text) => (/^"(.*)"$/s.test(text) ? text.replace(/^"(.*)"$/s, '$1') : text)

/**
 * Strip Sass interpolation, which no consumer outside Sass can read.
 *
 * Fifteen values are wrapped in `#{…}` — the escape hatch Bootstrap uses to smuggle a
 * `url()`, an aspect ratio like `#{"1 / 1"}` or a comma-separated shadow list past Sass's
 * own parsing. Left in, Style Dictionary reads the braces as a token reference and fails on
 * 27 of them; a designer opening the file sees syntax rather than a value.
 *
 * A parenthesised list of quoted strings is Sass's way of writing one comma-separated CSS
 * value, so it becomes exactly that.
 */
function desass(text) {
  const interpolated = /^#\{(.*)\}$/s.exec(text)
  if (!interpolated) return text

  const inner = interpolated[1].trim()
  const list = /^\((.*)\)$/s.exec(inner)
  if (list) {
    return splitTopLevel(list[1])
      .map((part) => unquote(part.trim()))
      .filter(Boolean)
      .join(', ')
  }
  return unquote(inner)
}

/**
 * The token's value with `{references}` intact — DTCG's own shape, as opposed to the CSS
 * `var()` form the Sass exporter needs.
 *
 * Arithmetic is the exception: `{spacing.base} * .25` is Sass, not something a downstream
 * tool can evaluate, so those are resolved to the literal they compute to. Losing the link
 * is the lesser harm — the alternative ships an expression nobody else can read.
 */
export function dtcgValue(doc, path, { mode = 'light' } = {}) {
  const token = doc.tokens.get(path)
  if (!token) return null
  const meta = ext(token)

  if (meta.arithmetic) return desass(doc.cssValueOf(path))
  if (mode === 'dark' && meta.dark) return desass(unquote(meta.dark))
  if (typeof token.$value !== 'string') return typedToCss(token)
  return desass(unquote(token.$value))
}

/* --------------------------------------------------------------------------
 * TypeScript
 * -------------------------------------------------------------------------- */

const jsString = (text) => JSON.stringify(String(text))

/**
 * A runtime module plus its declarations, rather than a `.ts` file.
 *
 * A `.ts` source only helps people who compile TypeScript; the pair works from plain
 * JavaScript, from TypeScript, and from a bundler, with no build step in between. That is
 * what published packages ship, and this is a published package.
 */
export function emitTypeScript(doc, { version, mode = 'light' } = {}) {
  const flat = flattenValues(doc, { mode })
  const dark = flattenValues(doc, { mode: 'dark' })

  const entries = []
  const paths = []
  for (const [path, token] of walk(doc.tree)) {
    const meta = ext(token)
    paths.push(path)

    const fields = [
      `cssVar: ${meta.cssVar ? jsString(meta.cssVar) : 'null'}`,
      `type: ${token.$type ? jsString(token.$type) : 'null'}`,
      `value: ${jsString(desass(unquote(doc.cssValueOf(path) ?? '')))}`
    ]
    if (flat.values.has(path)) fields.push(`light: ${jsString(flat.values.get(path))}`)
    if (dark.values.has(path)) fields.push(`dark: ${jsString(dark.values.get(path))}`)
    if (token.$description) fields.push(`description: ${jsString(token.$description)}`)

    entries.push(`  ${jsString(path)}: { ${fields.join(', ')} }`)
  }

  const runtime = `/**
 * Bootstrap ${version} design tokens.
 *
 * Generated by \`bstokens build\`. Do not edit.
 *
 * \`value\` is the CSS the token compiles to, which usually contains \`var()\` — that is what
 * keeps Bootstrap's runtime theming working, so prefer \`ref(path)\` over a frozen colour.
 * \`light\` and \`dark\` are those values resolved to literals, for the times you genuinely
 * cannot use the cascade: a canvas, a chart library, a native view.
 */

export const bootstrapVersion = ${jsString(version)}

export const tokens = {
${entries.join(',\n')}
}

/** The custom property a token is published under, or null if it has none. */
export function cssVar(path) {
  return tokens[path]?.cssVar ?? null
}

/**
 * \`var(--x)\`, ready to drop into a style object.
 *
 * Throws on an unknown path rather than returning a string that silently does nothing:
 * a typo in a token name should fail where you made it, not three screens later.
 */
export function ref(path, fallback) {
  const token = tokens[path]
  if (!token) throw new Error(\`Unknown token "\${path}"\`)
  if (!token.cssVar) throw new Error(\`Token "\${path}" has no custom property; use value(path)\`)
  return fallback === undefined ? \`var(\${token.cssVar})\` : \`var(\${token.cssVar}, \${fallback})\`
}

/** The resolved literal for a scheme, or undefined when the token has none. */
export function literal(path, scheme = 'light') {
  return scheme === 'dark' ? tokens[path]?.dark : tokens[path]?.light
}

/** Every token whose path starts with \`prefix\`, e.g. \`group('color.blue')\`. */
export function group(prefix) {
  const at = \`\${prefix}.\`
  return Object.fromEntries(Object.entries(tokens).filter(([path]) => path.startsWith(at)))
}
`

  const declarations = `/** Bootstrap ${version} design tokens. Generated by \`bstokens build\`. Do not edit. */

export type TokenPath =
${paths.map((path) => `  | ${jsString(path)}`).join('\n')}

export interface Token {
  /** The custom property this token is published under, or null if it has none. */
  readonly cssVar: string | null
  /** The DTCG type, or null for values DTCG cannot express. */
  readonly type: string | null
  /** The CSS this token compiles to. Usually contains \`var()\`. */
  readonly value: string
  /** The value resolved to a literal in light mode, when one can be computed. */
  readonly light?: string
  /** The value resolved to a literal in dark mode, when one can be computed. */
  readonly dark?: string
  readonly description?: string
}

export declare const bootstrapVersion: string
export declare const tokens: { readonly [P in TokenPath]: Token }
export declare function cssVar(path: TokenPath): string | null
export declare function ref(path: TokenPath, fallback?: string): string
export declare function literal(path: TokenPath, scheme?: 'light' | 'dark'): string | undefined
export declare function group(prefix: string): Partial<Record<TokenPath, Token>>
`

  return { 'tokens.js': runtime, 'tokens.d.ts': declarations }
}

/* --------------------------------------------------------------------------
 * Style Dictionary
 * -------------------------------------------------------------------------- */

/** The document as a nested DTCG tree, values in `{reference}` form. */
function dtcgTree(doc, { mode, only = null }) {
  const out = {}

  for (const [path, token] of walk(doc.tree)) {
    if (only && !only.has(path)) continue
    const value = dtcgValue(doc, path, { mode })
    if (value === null || value === 'null') continue

    const segments = path.split('.')
    let node = out
    for (const segment of segments.slice(0, -1)) node = node[segment] ??= {}
    node[segments.at(-1)] = {
      ...(token.$type ? { $type: token.$type } : {}),
      $value: value,
      ...(token.$description ? { $description: token.$description } : {})
    }
  }

  return out
}

/** Tokens whose dark value differs from their light one. */
function darkPaths(doc) {
  const paths = new Set()
  for (const [path, token] of walk(doc.tree)) if (ext(token).dark) paths.add(path)
  return paths
}

/**
 * Source files and configs that produce Bootstrap's own CSS shape.
 *
 * References are kept rather than resolved, because that is the whole reason to hand tokens
 * to Style Dictionary: a pipeline that can see `theme.primary` pointing at `color.blue.500`
 * can re-skin, and one that receives 1200 literals can only re-print.
 *
 * Dark mode is a second config rather than a second platform, because a Style Dictionary
 * config has one source set. `include` loads the light tokens so the dark ones can still
 * reference `{color.gray.050}` — but included tokens are still emitted, so the config also
 * filters on `isSource`. That is a function, which is why the dark config is JavaScript
 * while the light one is plain JSON: the dark stylesheet has to hold only the values that
 * change, or `[data-bs-theme=dark]` becomes a second copy of the whole document and wins
 * every cascade it should not.
 */
export function emitStyleDictionary(doc, { version } = {}) {
  const dark = darkPaths(doc)
  const note = `Bootstrap ${version} design tokens. Generated by \`bstokens build\`. Do not edit.`

  return {
    'tokens.json': `${JSON.stringify(dtcgTree(doc, { mode: 'light' }), null, 2)}\n`,
    'tokens.dark.json': `${JSON.stringify(dtcgTree(doc, { mode: 'dark', only: dark }), null, 2)}\n`,
    'config.json': `${JSON.stringify(
      {
        $comment: `${note} Run: npx style-dictionary build --config config.json`,
        source: ['tokens.json'],
        platforms: {
          css: {
            // Naming only, deliberately: `transformGroup: "css"` would run Style
            // Dictionary's colour transforms over values that are already valid CSS, and
            // they do not understand `color-mix()`, `light-dark()` or `oklch()`. Left on,
            // `rgb(0 0 0 / 65%)` comes back as `#000000` — the alpha silently gone.
            transforms: ['name/kebab'],
            buildPath: 'css/',
            files: [{ destination: 'variables.css', format: 'css/variables' }]
          }
        }
      },
      null,
      2
    )}\n`,
    'config.dark.mjs': `// ${note}
// Run: npx style-dictionary build --config config.dark.mjs
//
// \`include\` resolves references against the light tokens without making them part of this
// build's output; the \`isSource\` filter is what actually keeps them out of the file.
export default {
  include: ['tokens.json'],
  source: ['tokens.dark.json'],
  platforms: {
    css: {
      transforms: ['name/kebab'],
      buildPath: 'css/',
      files: [
        {
          destination: 'variables-dark.css',
          format: 'css/variables',
          filter: (token) => token.isSource,
          options: { selector: '[data-bs-theme=dark]' }
        }
      ]
    }
  }
}
`
  }
}

/* --------------------------------------------------------------------------
 * Tokens Studio (Figma)
 * -------------------------------------------------------------------------- */

/**
 * DTCG types are not Tokens Studio types, and the gap is not cosmetic: Tokens Studio uses
 * the type to decide which Figma property a token can be bound to. Mapping every dimension
 * to one bucket would leave a designer unable to apply a radius as a radius.
 */
function studioType(path, token) {
  const type = token.$type
  if (type === 'color') return 'color'
  if (type === 'fontWeight') return 'fontWeights'
  if (type === 'fontFamily') return 'fontFamilies'
  if (type === 'shadow') return 'boxShadow'
  if (type === 'dimension') {
    if (/(^|\.)radius/.test(path) || path.includes('border-radius')) return 'borderRadius'
    if (path.includes('border-width') || path.endsWith('.width')) return 'borderWidth'
    if (/(^|\.)spacing/.test(path) || /\.(padding|margin|gap)/.test(path)) return 'spacing'
    if (path.includes('font-size')) return 'fontSizes'
    if (path.includes('line-height')) return 'lineHeights'
    return 'sizing'
  }
  if (type === 'number') {
    if (path.includes('opacity')) return 'opacity'
    if (path.includes('line-height')) return 'lineHeights'
    return 'other'
  }
  return 'other'
}

/**
 * A Tokens Studio file, with light and dark as two sets.
 *
 * Everything is flat: Figma has no cascade, no `var()` and no `color-mix()`, so a reference
 * is not something it can hold. What it *can* hold is the colour a user actually sees, and
 * `flattenValues` computes exactly that, verified against a browser.
 *
 * Tokens with no computable value are left out and listed separately rather than filled in
 * with a plausible colour. A designer working from a palette that quietly invented eight
 * swatches is worse off than one working from a palette that says what it does not know.
 */
export function emitTokensStudio(doc, { version } = {}) {
  const sets = {}
  const dropped = {}

  for (const mode of ['light', 'dark']) {
    const { values, unresolved, contextual } = flattenValues(doc, { mode })
    const set = {}

    for (const [path, token] of walk(doc.tree)) {
      const value = values.get(path)
      if (value === undefined) continue

      const segments = path.split('.')
      let node = set
      for (const segment of segments.slice(0, -1)) node = node[segment] ??= {}
      node[segments.at(-1)] = {
        value,
        type: studioType(path, token),
        ...(token.$description ? { description: token.$description } : {}),
        ...(contextual.has(path)
          ? {
              $extensions: {
                'dev.bootstrap.tokens': {
                  contextual: contextual.get(path),
                  note: 'This value depends on which component the element sits in; the flat value is the default one.'
                }
              }
            }
          : {})
      }
    }

    sets[mode] = set
    dropped[mode] = Object.fromEntries([...unresolved].sort())
  }

  const file = {
    ...sets,
    $themes: ['light', 'dark'].map((mode) => ({
      id: mode,
      name: `Bootstrap ${mode}`,
      selectedTokenSets: { [mode]: 'enabled' }
    })),
    $metadata: { tokenSetOrder: ['light', 'dark'] }
  }

  return {
    'tokens.json': `${JSON.stringify(file, null, 2)}\n`,
    'not-exported.json': `${JSON.stringify(
      {
        $comment: `Bootstrap ${version} tokens with no value Figma can hold, and why. Nothing here was guessed at.`,
        ...dropped
      },
      null,
      2
    )}\n`
  }
}
